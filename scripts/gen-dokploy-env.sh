# TURN hostname (DNS-only, not proxied by Cloudflare). Empty means DOMAIN.
LIVEKIT_TURN_DOMAIN=
# Optional S3 / Cloudflare R2 instead of the bundled MinIO. Leave all empty for MinIO.
S3_ENDPOINT_URL=
