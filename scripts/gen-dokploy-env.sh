#!/usr/bin/env bash
# Generate the production env for the Dokploy stack, with fresh strong secrets.
#
# Usage:  ./scripts/gen-dokploy-env.sh [--force] [--output FILE] [domain]
#   domain     the public hostname, e.g. tara.example.com (optional: if left
#              out, DOMAIN stays empty and the stack refuses to start until set)
#   --output   where to write (default: .env_prod in the current directory)
#   --force    overwrite an existing output file
#
# Paste the result into Dokploy's Environment tab, then fill the
# "OWNER MUST FILL" block at the top. Run it ONCE per deployment: new database
# passwords do not reach an existing Postgres volume, and a new JWT key signs
# everyone out. The output holds live secrets; never commit it (.gitignore
# ignores .env_*). The variable reference is .env_prod.example.
set -euo pipefail

output=.env_prod
force=false
DOMAIN=""
while [ $# -gt 0 ]; do
  case "$1" in
    --force) force=true ;;
    --output) output="${2:?--output needs a file}"; shift ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *) DOMAIN="$1" ;;
  esac
  shift
done

if [ -e "$output" ] && [ "$force" != true ]; then
  echo "$output already exists; it holds live secrets. Pass --force to overwrite it." >&2
  exit 1
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }
secret() { openssl rand -hex 32; }   # 64 hex chars: Django keys, HMAC secrets
pw()     { openssl rand -hex 18; }   # 36 hex chars: passwords (URL-safe)
b64url() { base64 | tr '+/' '-_' | tr -d '=\n'; }
oneline() { awk 'BEGIN{ORS="\\n"} {print}' | sed 's/\\n$//'; }   # PEM -> one line, literal \n

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Web Push (VAPID) key pair as raw P-256 keys, base64url, the form pywebpush and
# browsers take. The DER private key holds the 32-byte scalar at offset 7 and
# ends with the 65-byte uncompressed public point.
openssl ecparam -name prime256v1 -genkey -noout -outform DER > "$tmp/vapid.der"
VAPID_PRIVATE=$(tail -c +8 "$tmp/vapid.der" | head -c 32 | b64url)
VAPID_PUBLIC=$(tail -c 65 "$tmp/vapid.der" | b64url)

# RS256 user-token signing pair (RSA-2048, PKCS#8), one line each.
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/jwt.pem" 2>/dev/null
openssl pkey -in "$tmp/jwt.pem" -pubout -out "$tmp/jwt.pub" 2>/dev/null
JWT_PRIVATE=$(oneline < "$tmp/jwt.pem")
JWT_PUBLIC=$(oneline < "$tmp/jwt.pub")

umask 077
cat > "$output" <<EOF
