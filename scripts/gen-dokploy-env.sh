#!/usr/bin/env bash
# Generate a production .env for the Dokploy stack with strong random secrets.
# Usage:  ./scripts/gen-dokploy-env.sh tara.example.com
#
# Writes .env.dokploy; paste it into Dokploy's Environment panel, then fill in
# the SMTP values. Run once: new passwords do not reach an existing database.
set -euo pipefail

DOMAIN="${1:?Usage: gen-dokploy-env.sh <domain>   e.g. tara.example.com}"
secret() { openssl rand -hex 32; }   # 64 hex chars
pw()     { openssl rand -hex 18; }   # 36 hex chars
b64url() { base64 | tr '+/' '-_' | tr -d '=\n'; }
# Web Push (VAPID) key pair as raw P-256 keys, base64url, the form pywebpush and
# browsers take. The DER private key holds the 32-byte scalar at offset 7 and
# ends with the 65-byte uncompressed public point.
vapid_der=$(mktemp)
trap 'rm -f "$vapid_der"' EXIT
openssl ecparam -name prime256v1 -genkey -noout -outform DER > "$vapid_der"
VAPID_PRIVATE=$(tail -c +8 "$vapid_der" | head -c 32 | b64url)
VAPID_PUBLIC=$(tail -c 65 "$vapid_der" | b64url)

output=.env.dokploy
if [ -e "$output" ]; then
  echo "$output already exists; it holds your live secrets. Move it away to regenerate." >&2
  exit 1
fi
umask 077

cat > "$output" <<EOF
# Generated by scripts/gen-dokploy-env.sh for ${DOMAIN}. DO NOT COMMIT.
DOMAIN=${DOMAIN}
TARA_ENV=production
TZ=UTC

# ---- Postgres (superuser + per-service least-privilege roles) -------------
POSTGRES_SUPERUSER=tara
POSTGRES_SUPERUSER_PASSWORD=$(pw)
POSTGRES_HOST=postgres
POSTGRES_PORT=5432
IDENTITY_DB_NAME=identity_db
IDENTITY_DB_USER=identity
IDENTITY_DB_PASSWORD=$(pw)
PROFILE_DB_NAME=profile_db
PROFILE_DB_USER=profile
PROFILE_DB_PASSWORD=$(pw)
GRAPH_DB_NAME=graph_db
GRAPH_DB_USER=graph
GRAPH_DB_PASSWORD=$(pw)
MEDIA_DB_NAME=media_db
MEDIA_DB_USER=media
MEDIA_DB_PASSWORD=$(pw)
POST_DB_NAME=post_db
POST_DB_USER=post
POST_DB_PASSWORD=$(pw)
FEED_DB_NAME=feed_db
FEED_DB_USER=feed
FEED_DB_PASSWORD=$(pw)
CHAT_DB_NAME=chat_db
CHAT_DB_USER=chat
CHAT_DB_PASSWORD=$(pw)
MARKET_DB_NAME=market_db
MARKET_DB_USER=market
MARKET_DB_PASSWORD=$(pw)
NOTIF_DB_NAME=notif_db
NOTIF_DB_USER=notif
NOTIF_DB_PASSWORD=$(pw)
SEARCH_DB_NAME=search_db
SEARCH_DB_USER=search
SEARCH_DB_PASSWORD=$(pw)
MODERATION_DB_NAME=moderation_db
MODERATION_DB_USER=moderation
MODERATION_DB_PASSWORD=$(pw)
ADMIN_DB_NAME=admin_db
ADMIN_DB_USER=adminsvc
ADMIN_DB_PASSWORD=$(pw)
ADS_DB_NAME=ads_db
ADS_DB_USER=ads
ADS_DB_PASSWORD=$(pw)

# ---- Redis ------------------------------------------------------------------
REDIS_PASSWORD=$(pw)

# ---- RabbitMQ / MinIO ------------------------------------------------------
RABBITMQ_USER=tara
RABBITMQ_PASS=$(pw)
MINIO_ROOT_USER=tara
MINIO_ROOT_PASSWORD=$(pw)
S3_BUCKET=tara-media
S3_REGION=us-east-1

# ---- Per-service Django secrets (unique) + internal token secret ----------
IDENTITY_SECRET_KEY=$(secret)
PROFILE_SECRET_KEY=$(secret)
GRAPH_SECRET_KEY=$(secret)
MEDIA_SECRET_KEY=$(secret)
POST_SECRET_KEY=$(secret)
FEED_SECRET_KEY=$(secret)
CHAT_SECRET_KEY=$(secret)
REALTIME_SECRET_KEY=$(secret)
MARKETPLACE_SECRET_KEY=$(secret)
NOTIFICATION_SECRET_KEY=$(secret)
SEARCH_SECRET_KEY=$(secret)
MODERATION_SECRET_KEY=$(secret)
ADMIN_SECRET_KEY=$(secret)
ADS_SECRET_KEY=$(secret)
INTERNAL_JWT_SECRET=$(secret)

# ---- DEBUG off everywhere --------------------------------------------------
IDENTITY_DEBUG=false
PROFILE_DEBUG=false
GRAPH_DEBUG=false
MEDIA_DEBUG=false
POST_DEBUG=false
FEED_DEBUG=false
CHAT_DEBUG=false
REALTIME_DEBUG=false
MARKETPLACE_DEBUG=false
NOTIFICATION_DEBUG=false
SEARCH_DEBUG=false
MODERATION_DEBUG=false
ADMIN_DEBUG=false
ADS_DEBUG=false

# ---- Allowed hosts: the public domain, the service's own name (internal
#      calls) and localhost (container healthcheck). -------------------------
IDENTITY_ALLOWED_HOSTS=${DOMAIN},identity,localhost,127.0.0.1
PROFILE_ALLOWED_HOSTS=${DOMAIN},profile,localhost,127.0.0.1
GRAPH_ALLOWED_HOSTS=${DOMAIN},graph,localhost,127.0.0.1
MEDIA_ALLOWED_HOSTS=${DOMAIN},media,localhost,127.0.0.1
POST_ALLOWED_HOSTS=${DOMAIN},post,localhost,127.0.0.1
FEED_ALLOWED_HOSTS=${DOMAIN},feed,localhost,127.0.0.1
CHAT_ALLOWED_HOSTS=${DOMAIN},chat,localhost,127.0.0.1
REALTIME_ALLOWED_HOSTS=${DOMAIN},realtime,localhost,127.0.0.1
MARKETPLACE_ALLOWED_HOSTS=${DOMAIN},marketplace,localhost,127.0.0.1
NOTIFICATION_ALLOWED_HOSTS=${DOMAIN},notification,localhost,127.0.0.1
SEARCH_ALLOWED_HOSTS=${DOMAIN},search,localhost,127.0.0.1
MODERATION_ALLOWED_HOSTS=${DOMAIN},moderation,localhost,127.0.0.1
ADMIN_ALLOWED_HOSTS=${DOMAIN},admin,localhost,127.0.0.1
ADS_ALLOWED_HOSTS=${DOMAIN},ads,localhost,127.0.0.1

# ---- JWT / tokens ----------------------------------------------------------
JWT_ISSUER=tara-identity
JWT_AUDIENCE=tara
IDENTITY_JWT_KEY_ID=prod-key-1
ACCESS_TOKEN_TTL_SECONDS=900
REFRESH_TOKEN_TTL_SECONDS=2592000

# ---- CORS / email / misc ---------------------------------------------------
IDENTITY_CORS_ORIGINS=https://${DOMAIN}
# Fill these in: without working SMTP nobody can verify an account.
EMAIL_HOST=
EMAIL_PORT=587
EMAIL_HOST_USER=
EMAIL_HOST_PASSWORD=
EMAIL_USE_TLS=true
DEFAULT_FROM_EMAIL=no-reply@${DOMAIN}
# New listings and ads wait for a moderator.
MARKETPLACE_AUTO_APPROVE=false
ADS_AUTO_APPROVE=false
# Web Push. Keep these keys: replacing them invalidates every browser subscription.
VAPID_PUBLIC_KEY=${VAPID_PUBLIC}
VAPID_PRIVATE_KEY=${VAPID_PRIVATE}
VAPID_SUBJECT=mailto:admin@${DOMAIN}
WEB_CONCURRENCY=2
LOG_LEVEL=INFO
EOF

echo "Wrote ${output} for ${DOMAIN}. Add your SMTP settings, then paste it into Dokploy."
