"""Stable experiment and rollout buckets, shared by every service and the web.

``bucket`` is FNV-1a (32 bit) over the UTF-16 code units of
``f"{account_id}:{key}"``: the same algorithm as
``frontend/web/src/stores/flags.ts::bucket``, so a flag or an experiment
assigns an account to the same bucket in the browser and on every server
(Tara Intelligence WP 5.4). Parity is checked on the ``% 100`` fold against a
fixture generated by running the web function under node; the ``% 10000`` fold
used for experiments is checked for its distribution only.

``assign_variant`` walks an experiment's variants in order with cumulative
``pct * 100`` (basis points of the 10,000 buckets) and returns the variant name,
or ``None`` when the account falls outside the allocated range (not in the
experiment). An experiment's ``salt`` changes the assignment without changing
its key.
"""

from __future__ import annotations

_OFFSET = 0x811C9DC5
_PRIME = 0x01000193
_MASK = 0xFFFFFFFF

EXPERIMENT_BUCKETS = 10_000


def _fnv1a_utf16(text: str) -> int:
    value = _OFFSET
    data = text.encode("utf-16-le")
    for i in range(0, len(data), 2):
        value ^= data[i] | (data[i + 1] << 8)
        value = (value * _PRIME) & _MASK
    return value


def bucket(account_id: str, key: str, buckets: int = 100) -> int:
    """The account's bucket in ``[0, buckets)`` for ``key``."""
    if buckets < 1:
        raise ValueError("buckets must be positive")
    return _fnv1a_utf16(f"{account_id}:{key}") % buckets


def assign_variant(account_id: str, experiment: dict) -> str | None:
    """The variant name ``account_id`` gets in ``experiment``, or ``None``.

    ``experiment`` is ``{key, salt, variants: [{name, pct, version, params}]}``;
    ``pct`` is a percentage (may be fractional, e.g. 12.5). Only ``key``,
    ``salt``, ``variants[].name`` and ``variants[].pct`` are read here.
    """
    key = str(experiment.get("key") or "")
    salt = str(experiment.get("salt") or "")
    variants = experiment.get("variants") or []
    if not key or not variants:
        return None
    b = bucket(str(account_id), f"{key}:{salt}", EXPERIMENT_BUCKETS)
    upper = 0
    for variant in variants:
        upper += round(float(variant.get("pct") or 0) * 100)
        if b < upper:
            return str(variant.get("name"))
    return None
