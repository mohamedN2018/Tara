"""WP 5.4: ``tara_common.bucketing``.

- Parity with the web's ``frontend/web/src/stores/flags.ts::bucket`` on the ``% 100``
  fold, on the checked-in fixture whose expected values were generated by running the
  web function under node (the web's vitest reads the same file).
- The ``% 10000`` fold that experiments use is tested for its distribution only:
  within +/-1% of each variant's share over 100k synthetic ids, and sticky.
"""

import json
import uuid
from collections import Counter
from pathlib import Path

from tara_common.bucketing import EXPERIMENT_BUCKETS, assign_variant, bucket

FIXTURE = Path(__file__).parent / "fixtures" / "bucket_parity.json"


def test_parity_with_flags_ts_on_the_percent_fold():
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert data["fold"] == 100
    cases = data["cases"]
    assert len(cases) >= 200
    # Non-ASCII keys and non-uuid ids are in the fixture (UTF-16 code units, not bytes).
    assert any(any(ord(ch) > 127 for ch in c["key"]) for c in cases)
    mismatched = [c for c in cases if bucket(c["account_id"], c["key"]) != c["expected"]]
    assert mismatched == []


def test_buckets_are_in_range_and_sticky():
    ids = [str(uuid.uuid4()) for _ in range(500)]
    for a in ids:
        b = bucket(a, "exp:s", EXPERIMENT_BUCKETS)
        assert 0 <= b < EXPERIMENT_BUCKETS
        assert b == bucket(a, "exp:s", EXPERIMENT_BUCKETS)


def test_distribution_within_one_percent_over_100k_ids():
    exp = {
        "key": "home.discovery_ratio",
        "salt": "s1",
        "variants": [
            {"name": "control", "pct": 34, "version": 6, "params": {}},
            {"name": "r15", "pct": 33, "version": 7, "params": {}},
            {"name": "r30", "pct": 33, "version": 8, "params": {}},
        ],
    }
    n = 100_000
    counts = Counter(assign_variant(str(uuid.UUID(int=i * 7919 + 13)), exp) for i in range(n))
    assert None not in counts
    for name, pct in (("control", 34), ("r15", 33), ("r30", 33)):
        assert abs(counts[name] / n - pct / 100) <= 0.01, (name, counts[name])


def test_unallocated_range_is_not_in_the_experiment_and_salt_reshuffles():
    exp = {"key": "k", "salt": "a", "variants": [{"name": "v", "pct": 10, "version": 1}]}
    ids = [str(uuid.uuid4()) for _ in range(5_000)]
    inside = [a for a in ids if assign_variant(a, exp) == "v"]
    assert 0.07 < len(inside) / len(ids) < 0.13
    other = {**exp, "salt": "b"}
    moved = sum(1 for a in inside if assign_variant(a, other) != "v")
    assert moved > len(inside) * 0.7  # a new salt is a new assignment
    assert assign_variant(ids[0], {"key": "", "variants": []}) is None
